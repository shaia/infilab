/**
 * The course map: every chapter, every planned lesson and every learning objective, written or not.
 *
 * Infinitesimal Calculus 1 as the Hebrew University teaches it (course 80131, Einstein Institute of
 * Mathematics). The official syllabus (shnaton, 2024–2026) lists the content as: the real numbers,
 * sequences of real numbers, limits of sequences, real functions of a real variable, limits of
 * functions, continuity, derivatives. Its learning outcome: know the formal-deductive structure, write
 * proofs, and solve problems in analysis. Chapters 1–5 follow that list in order. Chapter 0 gives a
 * first-time learner the language of proof the course assumes, and chapter 6 holds the topics the
 * 80132 (Infi 2) syllabus names as "completions of Infi 1" (lim sup / lim inf, uniform continuity,
 * L'Hôpital) plus Taylor's polynomial: taught in some semesters of 80131 and not in others, so they
 * sit beyond the syllabus until /exam-map settles them on real exams.
 *
 * Objectives live here, not only in lesson front matter, so that the question banks of every chapter
 * can exist before its lessons are written: a student can practise a chapter from day one. A written
 * lesson must declare exactly the objectives listed here (lint-content checks it).
 *
 * Objective texts are plain text (lesson header, My Path, the test report): no TeX. A formula that
 * cannot be said in words is wrapped in U+2066 … U+2069 (LRI … PDI) with no-break spaces inside.
 */

export interface Objective {
  id: string;
  text: string;
}

export interface PlannedLesson {
  id: string;
  title: string;
  objectives: Objective[];
  /** a topic whose place in 80131 is unverified: the lesson is marked so until /exam-map settles it */
  enrichment?: boolean;
}

export interface Chapter {
  n: number;
  title: string;
  /** one line under the chapter title on the contents page */
  blurb: string;
  /** beyond the 80131 syllabus: labelled so on the contents page and in its lessons */
  beyondSyllabus?: boolean;
  lessons: PlannedLesson[];
}

/** Builds a lesson's objectives from their texts: OBJ-<lesson>-1, -2, … in order. */
const L = (id: string, title: string, texts: string[], extra: { enrichment?: boolean } = {}): PlannedLesson => ({
  id,
  title,
  objectives: texts.map((text, i) => ({ id: `OBJ-${id}-${i + 1}`, text })),
  ...extra,
});

